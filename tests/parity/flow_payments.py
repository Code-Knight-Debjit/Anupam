"""Payment Collection flows (list, form, view, receive, history, payment log)."""
from harness import *
from flow_dashboard import check
from flow_customers import login, ok_dialog

def go(pg, h): pg.evaluate(f"location.hash='#/{h}'"); pg.wait_for_timeout(1500)

def run(p):
    ok = True; b = launch(p)
    ctx, pg = login(b, 'admin', geo=False)
    go(pg, 'payments')
    txt = pg.inner_text('#paymentStatsRow')
    ok &= check('D stat tiles: total, pending, collected', '80,000' in txt and '30,000' in txt and '50,000' in txt, txt)
    ok &= check('D only payments with a balance are listed, grouped per branch', pg.locator('.pay-branch-head').count() == 1 and 'Chennai' in pg.inner_text('.pay-branch-head') and pg.locator('#paymentsTableWrap tr').count() == 2, pg.inner_text('#paymentsTableWrap'))
    ok &= check('D row shows the balance, not the amount', '₹30,000' in pg.inner_text('#paymentsTableWrap'))
    ok &= check('D contact cell has Last contact / Call later lines', 'Last contact: —' in pg.inner_text('#paymentsTableWrap') and 'Call later: —' in pg.inner_text('#paymentsTableWrap'))
    pg.click('#paymentFilterToggleBtn'); pg.select_option('#fltPayBranch', 'Chennai'); pg.wait_for_timeout(300)
    ok &= check('D filter badge counts the active filters', pg.inner_text('#paymentFilterBadge') == '1')
    pg.fill('#fltPaySearch', 'zzz'); pg.wait_for_timeout(300)
    ok &= check('D empty state', 'No payments due' in pg.inner_text('#paymentsTableWrap'))
    pg.click('#fltPayClear'); pg.wait_for_timeout(300)
    pg.click('#paymentViewAllBtn'); pg.wait_for_timeout(300)
    ok &= check('D View All toggles to Undo', pg.inner_text('#paymentViewAllBtn') == 'Undo View All'); pg.click('#paymentViewAllBtn')
    # View
    pg.locator('[data-pay-act="view"]').first.click(); pg.wait_for_timeout(500)
    ok &= check('D Payment Overview dialog', '₹50,000' in pg.inner_text('#pvTotal') and '₹20,000' in pg.inner_text('#pvReceived') and '₹30,000' in pg.inner_text('#pvBalance') and pg.locator('#pvReceipts tr').count() == 1)
    pg.click('#paymentViewCloseBtn'); pg.wait_for_timeout(300)
    # Payment log
    pg.locator('[data-paylog]').first.click(); pg.wait_for_timeout(1500)
    ok &= check('D Payment Log page', pg.inner_text('#contactLogTitle') == 'Payment Log' and 'Rs' not in pg.inner_text('#contactLogSub') and '₹50,000' in pg.inner_text('#contactLogSub'), pg.inner_text('#contactLogSub'))
    pg.fill('#contactLogInput', 'Promised by Friday'); pg.click('#contactLogSendBtn'); pg.wait_for_timeout(1000)
    ok &= check('D payment log message added', 'Promised by Friday' in pg.inner_text('#contactLogMessages'))
    pg.click('#clSuggestCallLater'); pg.click('#clCallLaterSendBtn'); pg.wait_for_timeout(1000)
    ok &= check('D call-later entry shows the follow-up', 'Call back on' in pg.inner_text('#contactLogMessages'))
    pg.click('#contactLogBackBtn'); pg.wait_for_timeout(1500)
    ok &= check('D list now shows last contact and call-later', 'Last contact: —' not in pg.inner_text('#paymentsTableWrap') and 'Call later: —' not in pg.inner_text('#paymentsTableWrap'))
    # Received payment
    pg.locator('[data-pay-act="receive"]').first.click(); pg.wait_for_timeout(500)
    ok &= check('D Received dialog defaults', pg.input_value('#rp-mode') == 'Cash' and '₹30,000' in pg.input_value('#rp-balance'))
    pg.click('#receivedPaymentSaveBtn'); pg.wait_for_timeout(300)
    ok &= check('D amount required', 'Enter an amount greater than zero.' in pg.inner_text('body')); ok_dialog(pg)
    pg.fill('#rp-amount', '40000'); pg.click('#receivedPaymentSaveBtn'); pg.wait_for_timeout(400)
    ok &= check('D more than the balance asks to confirm', "Only ₹30,000.00 is due, but you're recording ₹40,000.00" in pg.inner_text('body')); pg.click('#dlgCancel'); pg.wait_for_timeout(400)
    pg.fill('#rp-amount', '10000'); pg.select_option('#rp-mode', 'UPI'); pg.click('#receivedPaymentSaveBtn'); pg.wait_for_timeout(1500)
    ok &= check('D partial receipt reduces the balance and moves the tiles', '₹20,000' in pg.inner_text('#paymentsTableWrap') and '₹60,000' in pg.inner_text('#paymentStatsRow'), pg.inner_text('#paymentStatsRow'))
    # New / edit form
    pg.click('#paymentNewBtn'); pg.wait_for_timeout(1500)
    ok &= check('D form page', pg.inner_text('#paymentFormTitle') == 'New Payment' and pg.input_value('#pay-date') != '')
    pg.click('#paymentFormSaveBtn'); ok &= check('D customer required', pg.inner_text('#paymentFormHint') == 'Select a customer.')
    pg.select_option('#pay-customer', index=1); pg.wait_for_timeout(800)
    ok &= check('D contacts load for the customer', pg.locator('#pay-contact option').count() > 1)
    pg.click('#paymentFormSaveBtn'); ok &= check('D amount required on the form', pg.inner_text('#paymentFormHint') == 'Enter an amount greater than zero.')
    pg.fill('#pay-amount', '12345'); pg.select_option('#pay-branch', ''); pg.click('#paymentFormSaveBtn')
    ok &= check('D branch required', pg.inner_text('#paymentFormHint') == 'Select the branch this amount belongs to.')
    pg.select_option('#pay-branch', index=1); pg.fill('#pay-remarks', 'INV-NEW'); pg.click('#paymentFormSaveBtn'); pg.wait_for_timeout(1800)
    ok &= check('D saving returns to the list with the new payment', '₹12,345' in pg.inner_text('#paymentsTableWrap'), pg.url)
    row = pg.locator('#paymentsTableWrap tr', has_text='12,345')
    row.locator('[data-pay-act="edit"]').click(); pg.wait_for_timeout(1500)
    ok &= check('D edit form prefilled', pg.inner_text('#paymentFormTitle') == 'Edit Payment' and pg.input_value('#pay-amount') == '12345' and pg.input_value('#pay-remarks') == 'INV-NEW')
    pg.fill('#pay-amount', '15000'); pg.click('#paymentFormSaveBtn'); pg.wait_for_timeout(1800)
    ok &= check('D edit saved', '₹15,000' in pg.inner_text('#paymentsTableWrap'))
    pg.locator('#paymentsTableWrap tr', has_text='15,000').locator('[data-pay-act="delete"]').click(); pg.wait_for_timeout(400); ok_dialog(pg); pg.wait_for_timeout(1200)
    ok &= check('D delete removes it', '15,000' not in pg.inner_text('#paymentsTableWrap'))
    # History
    pg.click('.row-menu-btn'); pg.click('#paymentHistoryBtn'); pg.wait_for_timeout(1500)
    ok &= check('D history: fully collected table', 'Hindustan' in pg.inner_text('#paymentHistCompletedWrap'), pg.inner_text('#paymentHistCompletedWrap'))
    ok &= check('D history: all receipts', pg.locator('#paymentHistTxWrap tr').count() >= 4, str(pg.locator('#paymentHistTxWrap tr').count()))
    ok &= check('D payments nav stays lit on the sub-pages', pg.locator('.nav-item.active[data-view="payments"]').count() == 1)
    pg.click('#paymentHistBackBtn'); pg.wait_for_timeout(1000)
    ok &= check('D back to the list', pg.locator('#paymentStatsRow').count() == 1)
    ctx.close()
    # P-05 roles: Branch Manager lands on their own branch; Sales Manager has no Payments entry and sees none of the others'
    ctx, pg = login(b, 'manager', geo=False); go(pg, 'payments')
    ok &= check('P-05 Branch Manager defaults to own branch (badge 1) and sees the payments', pg.inner_text('#paymentFilterBadge') == '1' and pg.locator('.pay-branch-head').count() >= 1, pg.inner_text('#paymentFilterBadge'))
    pg.click('#paymentViewAllBtn'); pg.wait_for_timeout(300)
    ok &= check('P-05 View All clears the branch default', not pg.is_visible('#paymentFilterBadge')); ctx.close()
    ctx, pg = login(b, 'sales', geo=False)
    ok &= check('P-05 Sales Manager has no Payment Collection entry', not pg.is_visible('#navPayments'))
    go(pg, 'payments'); ok &= check('P-05 and no one else\'s payments', 'Sundaram' not in pg.inner_text('#paymentsTableWrap'))
    ctx.close(); b.close()
    print('PAYMENTS PASS' if ok else 'PAYMENTS FAILED')

if __name__ == '__main__':
    with sync_playwright() as p: run(p)
