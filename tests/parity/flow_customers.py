def login(b, user, geo=True):
    kw = dict(viewport={'width': 1440, 'height': 900})
    if geo: kw.update(geolocation={'latitude': 13.0287, 'longitude': 77.5197}, permissions=['geolocation'])
    ctx = b.new_context(**kw); pg = ctx.new_page(); pg.goto(APP + 'login/'); app_login(pg, user)
    pg.evaluate("location.hash='#/customers'"); pg.wait_for_timeout(1800); return ctx, pg

def ok_dialog(pg):
    pg.wait_for_selector('#dlgOk', timeout=5000); pg.click('#dlgOk'); pg.wait_for_timeout(600)

