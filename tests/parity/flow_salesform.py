"""Scripted Sales form flows (cases S-07..S-11, S-16)."""
from harness import *
from flow_dashboard import check
from flow_customers import login, ok_dialog

def go(pg, h): pg.evaluate(f"location.hash='#/{h}'"); pg.wait_for_timeout(1500)

def run(p):
    ok = True; b = launch(p)
    ctx, pg = login(b, 'admin', geo=False)
    go(pg, 'salesform/quotation/new')
    ok &= check('S-07 number previewed before a branch is chosen', 'QUO-0001' in pg.inner_text('#salesModalSub') or 'QUO-' in pg.inner_text('#salesModalSub'), pg.inner_text('#salesModalSub'))
    pg.click('#salesSaveBtn'); pg.wait_for_timeout(500)
    ok &= check('S-07 customer required', 'Select a customer first.' in pg.inner_text('.overlay.open .modal')); ok_dialog(pg)
    pg.select_option('#sf-customer', label='Sundaram Fasteners Ltd, Plant 3, Peenya Industrial Area'); pg.wait_for_timeout(300)
    ok &= check('S-07 customer address shown', 'Peenya' in pg.inner_text('#sf-customer-address'))
    ok &= check('S-07 contacts follow the customer', pg.locator('#sf-contact option').count() == 4)
    pg.click('#salesSaveBtn'); pg.wait_for_timeout(400)
    ok &= check('S-07 branch required', 'Select a branch first.' in pg.inner_text('.overlay.open .modal')); ok_dialog(pg)
    pg.select_option('#sf-branch', label='Chennai'); pg.wait_for_timeout(500)
    pg.click('#salesSaveBtn'); pg.wait_for_timeout(400)
    ok &= check('S-08 at least one item', 'Add at least one item.' in pg.inner_text('.overlay.open .modal')); ok_dialog(pg)
    pg.select_option('#sf-contact', index=1); pg.select_option('#sf-ref', label='ENQ-0001 — Sundaram Fasteners Ltd')
    row = pg.locator('.sales-item-row').first
    row.locator('.si-itemName').fill('6205 2RS bearing'); row.locator('.si-qty').fill('10'); row.locator('.si-rate').fill('200'); row.locator('.si-discount').fill('10')
    pg.wait_for_timeout(300)
    ok &= check('S-09 line amount = rate after discount + 18% tax', '₹212.40' in pg.inner_text('.sales-item-row .si-amount') and '₹2,124.00' in pg.inner_text('.sales-item-row .si-value'))
    pg.fill('#sf-packing', '100'); pg.wait_for_timeout(300)
    ok &= check('S-09 sub total, charge tax and auto round-off', '₹2,124.00' in pg.inner_text('#sf-subtotal') and '₹2,242.00' in pg.inner_text('#sf-totalamount'), pg.inner_text('#sf-totalamount'))
    pg.check('#sf-showdiscount'); pg.wait_for_timeout(200)
    pg.fill('#sf-roundoff', '1.00'); pg.wait_for_timeout(200)
    ok &= check('S-09 manual round-off is respected, (auto) restores it', '₹2,243.' in pg.inner_text('#sf-totalamount'))
    pg.click('#sf-roundoff-auto'); pg.wait_for_timeout(200)
    pg.locator('.sales-item-row').nth(1).locator('.si-itemName').fill('Second item'); pg.locator('.sales-item-row').nth(1).locator('.si-qty').fill('1'); pg.locator('.sales-item-row').nth(1).locator('.si-rate').fill('50')
    pg.locator('.sales-item-row').nth(1).locator('[data-move="-1"]').click(); pg.wait_for_timeout(200)
    ok &= check('S-08 move up reorders rows', pg.locator('.sales-item-row').first.locator('.si-itemName').input_value() == 'Second item')
    pg.fill('#sf-terms', 'Only line one'); pg.click('#salesSaveBtn'); pg.wait_for_timeout(1800)
    ok &= check('S-07 linked enquiry marked Completed message', 'Completed' in pg.inner_text('.overlay.open .modal'), pg.inner_text('.overlay.open .modal')[:100]); ok_dialog(pg)
    ok &= check('S-07 print/PDF offer after save', 'saved' in pg.inner_text('.overlay.open .modal').lower()); pg.click('#pp-skip'); pg.wait_for_timeout(800)
    ok &= check('S-07 back on the quotation list with the new number', 'Second item' in pg.inner_text('#salesTableWrap') or 'Sundaram' in pg.inner_text('#salesTableWrap'))
    # edit
    pg.locator('.row-menu-btn:has-text("Menu")').first.click(); pg.locator('.row-menu-dropdown.open [data-act="edit"]').click(); pg.wait_for_timeout(1500)
    ok &= check('S-07 edit form is prefilled (customer locked, items, terms)', pg.is_disabled('#sf-customer') and 'Only line one' in pg.input_value('#sf-terms') and pg.locator('.sales-item-row').count() >= 2)
    pg.fill('#sf-remarks', 'edited remark'); pg.click('#salesSaveBtn'); pg.wait_for_timeout(1800); pg.click('#pp-skip'); pg.wait_for_timeout(500)
    go(pg, 'sales/quotation')
    pg.locator('.row-menu-btn:has-text("Menu")').first.click(); pg.locator('.row-menu-dropdown.open [data-act="clone"]').click(); pg.wait_for_timeout(1500)
    ok &= check('S-07 clone page title and a fresh number', 'Clone of Quotation' in pg.inner_text('#salesModalTitle') and pg.input_value('#sf-docnumber').startswith('QUO-'))
    pg.click('#salesCancelBtn'); pg.wait_for_timeout(800)
    # PO
    go(pg, 'salesform/po/new')
    ok &= check('S-08 PO form has Ordered Qty and no Tax column, no charges block', 'ordered qty' in pg.inner_text('#salesItemHead').lower() and 'tax' not in pg.inner_text('#salesItemHead').lower() and not pg.is_visible('#salesChargesSection'))
    ok &= check('S-08 PO number is typed, not generated', pg.input_value('#sf-docnumber') == '' and pg.is_visible('#sf-status'))
    pg.select_option('#sf-branch', label='Chennai'); pg.select_option('#sf-customer', label='Hindustan Gearbox Works, Ambattur')
    pg.locator('.sales-item-row').first.locator('.si-itemName').fill('NU 310'); pg.locator('.sales-item-row').first.locator('.si-qty').fill('4'); pg.locator('.sales-item-row').first.locator('.si-rate').fill('100')
    pg.fill('#sf-docnumber', 'CUST-PO-555'); pg.click('#salesSaveBtn'); pg.wait_for_timeout(1800)
    ok &= check('S-08 PO saved with the typed number', 'CUST-PO-555' in pg.inner_text('#salesTableWrap'))
    go(pg, 'salesform/dc/new')
    ok &= check('S-08 DC form: vehicle + transport, no sales person / valid-till / payment terms', all(pg.is_visible(s) for s in ('#sf-vehicle', '#sf-transport')) and not pg.is_visible('#sf-salesperson') and not pg.is_visible('#sf-validtill') and not pg.is_visible('#sf-paymentterms'))
    go(pg, 'salesform/enquiry/new')
    ok &= check('S-08 enquiry has Source of Enquiry and no items', 'source of enquiry' in pg.inner_text('#sf-source-label').lower() and not pg.is_visible('#salesItemsSection'))
    ctx.close()
    ctx, pg = login(b, 'sales', geo=False)
    go(pg, 'sales/quotation')
    ok &= check('S-11 SM sees quotations but no Menu edit/clone', pg.locator('[data-act="edit"]').count() == 0)
    go(pg, 'salesform/enquiry/new')
    pg.select_option('#sf-branch', label='Chennai'); pg.select_option('#sf-customer', label='Deccan Agro Equipments, Hebbal'); pg.click('#salesSaveBtn'); pg.wait_for_timeout(1500)
    pg.click('[data-act="edit"] >> nth=0'); pg.wait_for_timeout(1500)
    pg.fill('#sf-remarks', 'SM change'); pg.click('#salesSaveBtn'); pg.wait_for_timeout(1500)
    ok &= check('S-11 SM enquiry edit goes for approval', 'submitted for approval' in pg.inner_text('.overlay.open .modal')); ok_dialog(pg)
    ctx.close(); b.close()
    print('ALL PASS' if ok else 'SOME FAILED')

if __name__ == '__main__':
    with sync_playwright() as p: run(p)
